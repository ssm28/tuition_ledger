"""Human-readable validation summary written next to every generated dataset."""
from __future__ import annotations

from collections import Counter

from .anomalies import ISSUE_CHECKS

FAMILIES = {
    "Primary-key uniqueness and ID format": ("pk_duplicate", "pk_format", "columns"),
    # joins: keys exist (fk_missing) and the rows on both sides of a join agree with each other
    "Foreign-key integrity": ("fk_missing", "invoice_enrollment_mismatch", "line_fee_schedule_missing",
                              "line_fee_type", "line_wrong_schedule", "line_schedule_not_effective",
                              "allocation_student_mismatch", "refund_student_mismatch", "refund_enrollment"),
    "Required fields, types and allowed values (enums)": ("required", "type", "enum"),
    "Date ordering": ("withdrawal_date", "invoice_due_date", "line_date", "allocation_date", "refund_dates",
                      "ledger_sequence", "ledger_date_or_student"),
    "Arithmetic reconciliation (totals, amounts, balances)": (
        "invoice_total_mismatch", "line_amount_mismatch", "line_sign", "invoice_status", "late_fee_missing",
        "late_fee_unexpected", "late_fee_wrong", "withdrawal_refund_amount", "cancellation_refund_amount",
        "refund_overpayment_amount", "ledger_amount_mismatch", "ledger_missing", "ledger_extra",
        "balance_ledger_mismatch", "scholarship_credit_mismatch", "scholarship_amount_mismatch"),
    "Lifecycle transitions": ("lifecycle_no_history", "lifecycle_chain", "lifecycle_transition",
                              "lifecycle_state_mismatch", "refund_processed_on"),
    "Duplicates": ("duplicate_invoice", "duplicate_enrollment", "duplicate_scholarship", "late_fee_duplicate",
                   "ledger_duplicate"),
    "Scholarship rules": ("scholarship_not_eligible", "scholarship_exceeds_cap", "scholarship_exceeds_fees",
                          "scholarship_no_invoice", "scholarship_credit_line", "scholarship_credit_wrong_invoice",
                          "waiver_target", "waiver_exceeds_fee"),
    "Allocation and refund limits": ("allocation_exceeds_payment", "allocation_exceeds_line", "allocation_amount",
                                     "allocation_to_non_charge_line", "refund_exceeds_net_paid",
                                     "refund_exceeds_payment", "refund_amount", "refund_rejected_but_eligible",
                                     "payment_amount"),
}


def render_validation_summary(meta: dict, tables: dict, baseline_issues: list, issues: list,
                              score: dict | None) -> str:
    out = ["# Validation summary", "",
           f"Seed `{meta['seed']}`, scale `{meta['scale']}`, as-of date `{meta['as_of']}`. "
           "Generated by `tuition-synth generate`; do not edit by hand.", "",
           "## Row counts", "", "| Table | Rows |", "|---|---:|"]
    out += [f"| `{name}` | {len(rows):,} |" for name, rows in tables.items()]
    out += ["", "## Clean baseline", "",
            f"The baseline is validated **before** anomalies are injected: **{len(baseline_issues)} issue(s)**."]
    if baseline_issues:
        out += ["", "Baseline problems (a generator bug):", ""]
        out += [f"- `{i.check}` {i.table} {i.row_id} {i.detail}" for i in baseline_issues[:20]]

    counts = Counter(i.check for i in issues)
    out += ["", "## Check families", "",
            "| Check family | Issues found in the delivered dataset |", "|---|---:|"]
    for family, checks in FAMILIES.items():
        out.append(f"| {family} | {sum(counts[c] for c in checks)} |")

    if score:
        out += ["", "## Injected anomalies (ground truth) vs. what the validator found", "",
                "| Issue type | Injected | Detected | Recall |", "|---|---:|---:|---:|"]
        for issue_type in ISSUE_CHECKS:
            s = score["per_type"].get(issue_type, {"injected": 0, "detected": 0})
            recall = f"{s['detected'] / s['injected']:.0%}" if s["injected"] else "n/a"
            out.append(f"| `{issue_type}` | {s['injected']} | {s['detected']} | {recall} |")
        out += ["", f"- Overall recall: **{score['detected']}/{score['injected']}** ({score['recall']:.0%}).",
                f"- Total issues raised: {score['issues_total']}; issues on rows that are neither injected nor "
                f"named as related to an injected anomaly (false alarms or collateral damage): "
                f"**{len(score['unexplained'])}**.",
                "- The validator reads only the data tables; `ground_truth` is used here for scoring only."]
    out += ["", "## Every check that fired", "", "| Check | Count |", "|---|---:|"]
    out += [f"| `{check}` | {n} |" for check, n in sorted(counts.items())]
    return "\n".join(out) + "\n"
